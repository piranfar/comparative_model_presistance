"""
Index everything in results/, and say which paper each output belongs to.

Run:  python -m src.build_results_index

This lists every output of the current paper, what wrote it and what consumes
it, generated from the files themselves so it cannot drift the way a
hand-written list would. The earlier paper's outputs are not here: they moved
with it to version_one/results/.

It also reports two things worth knowing rather than discovering: outputs that
no script and no manuscript uses, and outputs kept deliberately even though
nothing cites them.

Writes results/README.md
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = RES / "README.md"

# Which experiments belong to which manuscript.
PAPERS = {
    "Rate versus duration (manuscript/PAPER_COMPLETE.md)":
        [f"exp{n}" for n in range(16, 22)] + ["fig10", "fig11", "fig12", "fig13"],
}

# Outputs retained on purpose although nothing currently cites them.
KEPT_DELIBERATELY = {
    "exp21_combination.csv":
        "the withdrawn combination result. Retained as the record of a claim "
        "this project made and then withdrew, so the withdrawal is auditable "
        "rather than invisible.",
    "exp18_kappa_sweep.csv":
        "the Hill-coefficient sweep. Computed while establishing that no "
        "verified mycobacterial source measures an exponent on the axis kappa "
        "occupies; the paper states that conclusion without reproducing the "
        "sweep.",
}


def owner(name: str) -> str:
    for paper, prefixes in PAPERS.items():
        if any(name.startswith(p) for p in prefixes):
            return paper
    return "Unassigned"


def cited_in_manuscripts(stem: str) -> bool:
    for m in (ROOT / "manuscript").glob("*.md"):
        if stem in m.read_text(encoding="utf-8", errors="replace"):
            return True
    return False


def read_by_scripts(name: str) -> list[str]:
    hits = []
    for s in list((ROOT / "src").rglob("*.py")):
        t = s.read_text(encoding="utf-8", errors="replace")
        if name in t:
            hits.append(str(s.relative_to(ROOT)).replace("\\", "/"))
    return hits


def main() -> int:
    tables = sorted(p.name for p in (RES / "tables").glob("*.csv"))
    figures = sorted({p.stem for p in (RES / "figures").glob("*.*")})
    receipts = sorted(p.name for p in (RES / "receipts").glob("*.json"))

    lines = [
        "# What is in results/",
        "",
        "Generated by `python -m src.build_results_index`. Every file here is "
        "written by a script in `src/` and can be regenerated by rerunning it; "
        "nothing in this directory is edited by hand.",
        "",
        "Outputs of the earlier paper are not here; they live in "
        "`version_one/results/`.",
        "",
        f"| | tables | figures | receipts |",
        f"| --- | ---: | ---: | ---: |",
        f"| total | {len(tables)} | {len(figures)} | {len(receipts)} |",
        "",
    ]

    for paper in list(PAPERS) + ["Unassigned"]:
        t = [x for x in tables if owner(x) == paper]
        f = [x for x in figures if owner(x) == paper]
        if not t and not f:
            continue
        lines += [f"## {paper}", ""]
        if f:
            lines += ["**Figures.** " + ", ".join(f"`{x}`" for x in f), ""]
        if t:
            lines += [f"**Tables ({len(t)}).**", ""]
            lines += ["| file | written by | used by |",
                      "| --- | --- | --- |"]
            for x in t:
                readers = [r for r in read_by_scripts(x)
                           if not r.endswith("build_results_index.py")]
                producer = next((r for r in readers if "experiments" in r), "-")
                consumers = [r.split("/")[-1].replace(".py", "")
                             for r in readers if "experiments" not in r]
                # A table with no consumer is not necessarily unused: several
                # are quoted as numbers in the manuscript text without passing
                # through a figure or table script. Only the two named under
                # "kept on purpose" below have no use at all.
                use = ", ".join(f"`{c}`" for c in consumers) or "quoted in the text only"
                lines.append(f"| `{x}` | `{producer.split('/')[-1]}` | {use} |")
            lines += [""]

    if KEPT_DELIBERATELY:
        lines += ["## Kept on purpose, though nothing cites them", ""]
        for name, why in KEPT_DELIBERATELY.items():
            lines += [f"- **`{name}`** — {why}", ""]

    lines += [
        "## Receipts",
        "",
        f"{len(receipts)} JSON receipts, one per analysis stage. Each records "
        "the inputs, the headline outputs and the software versions the stage "
        "actually ran under, so a run under different versions is recorded "
        "rather than silently substituted.",
        "",
        "## Checking the numbers",
        "",
        "`python -m src.audit_claims` recomputes every quantity quoted in the "
        "manuscripts from the table it came from and reports any that disagree.",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    for paper in list(PAPERS) + ["Unassigned"]:
        n_t = sum(1 for x in tables if owner(x) == paper)
        n_f = sum(1 for x in figures if owner(x) == paper)
        if n_t or n_f:
            print(f"   {paper[:58]:<60} {n_t:>3} tables, {n_f:>2} figures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
